def dialog_title(cls: type, menu: str | None = None) -> str:
    """A dialog's window title: the class's ``dialog_title``, else the table's, else its menu label without the
    ellipsis, else its class name in words (FigureOptions -> "Figure options")."""
    if getattr(cls, "dialog_title", ""):
        return cls.dialog_title  # type: ignore[attr-defined]
    if cls.__name__ in TITLES:
        return TITLES[cls.__name__]
    if menu:
        return menu_label(menu).rstrip(".… ")
    words = re.findall(r"[A-Z][a-z]*|[a-z]+", cls.__name__)
    return " ".join([words[0], *(w.lower() for w in words[1:])]) if words else cls.__name__



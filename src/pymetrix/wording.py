def stat_group(label: str) -> str:
    """The group a summary statistic's label goes under (``STAT_GROUPS``): "Other" for a label no prefix knows."""
    key = label.strip().lower()
    best = max((p for p in STAT_GROUP_PREFIXES if key.startswith(p)), key=len, default=None)
    return STAT_GROUP_PREFIXES[best] if best is not None else "Other"


def is_known_stat(label: str) -> bool:
    """Whether a label is one ``STAT_GROUP_PREFIXES`` knows."""
    key = label.strip().lower()
    return any(key.startswith(p) for p in STAT_GROUP_PREFIXES)



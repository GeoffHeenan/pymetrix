def fallback_label(name: str) -> str:
    """The words of an argument name, for a setting the table does not know: ``max_lags`` -> "Max lags"."""
    words = name.strip("_").replace("_", " ")
    return words[:1].upper() + words[1:]


def field_label(owner: str, name: str, explicit: str = "") -> str:
    """The label of the setting ``name`` of ``owner`` (a command's or a settings class's name): the command's own
    override, else the field's ``Widget(label=...)``, else the shared table, else the argument name's words."""
    return COMMAND_LABELS.get(owner, {}).get(name) or explicit or FIELD_LABELS.get(name) or fallback_label(name)


def is_mapped(owner: str, name: str, explicit: str = "") -> bool:
    """Whether the label comes from a table or the field itself (rather than from the argument name)."""
    return bool(COMMAND_LABELS.get(owner, {}).get(name) or explicit or FIELD_LABELS.get(name))


def python_hint(name: str) -> str:
    """How scripts write the setting, for the field's tooltip: "Python: exog="."""
    return f"Python: {name}="



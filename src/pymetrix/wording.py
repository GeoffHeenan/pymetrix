"""The words the app shows for settings: field labels, the names of fixed choices, dialog titles and the glossary.

One table for every dialog, the core's and plugins': a setting is labelled by its argument name (``exog`` reads
"Exogenous series" wherever it appears), with per-command overrides where one name means different things (``low`` is
"Low-frequency data" in MIDAS, ``periods`` is "Horizon" in Impulse responses). A ``Widget(label=...)`` on the field
itself comes before the shared table, a per-command override before both. A name the table does not know (a new
plugin's) falls back to its words, ``max_lags`` -> "Max lags".

Choices work the same way: the stored value, and so the recorded script, stays the code (``method='fmols'``); the
form shows its name ("FM-OLS (fully modified)"), and the code in the item's tooltip.

The words follow the glossary at the end (``GLOSSARY``): a column of data is a *series*; *variable* is kept for a
model's variables; the active window of periods is the *sample*, set by Start and End; *estimate* in menus (``fit``
in code); *Horizon* for steps ahead; *Draws* (Bayesian) and *Replications* (bootstrap). Spelling is British, as in
the docs. Labels are sentence case with no trailing colon.

This module has no UI dependencies: forms, help pages and tests read it.
"""


def _copula_names() -> dict[str, str]:
    """Copula families with their rotations: "clayton180" -> "Clayton, rotated 180° (survival)"."""
    names = {"clayton": "Clayton", "gumbel": "Gumbel", "joe": "Joe", "bb1": "BB1", "bb6": "BB6", "bb7": "BB7", "bb8": "BB8",
             "tawn1": "Tawn type 1", "tawn2": "Tawn type 2"}
    out = {code: name for code, name in names.items()}
    for code, name in names.items():
        for turn in ("90", "180", "270"):
            words = f"{name}, rotated {turn}°" + (" (survival)" if turn == "180" else "")
            out[code + turn] = out[f"{code}_{turn}"] = words
    return out



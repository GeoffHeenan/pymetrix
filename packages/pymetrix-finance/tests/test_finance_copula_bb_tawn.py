def test_vine_loglik_against_r():
    i = np.arange(1, 41)[:, None]
    u = 0.01 + 0.98 * ((i * np.array([0.6180339887, 0.4142135624, 0.7320508076, 0.2360679775])) % 1)
    trees = V.from_matrix(M4, F4, P4, Q4)
    ll = V.propagate(u, trees)[0]
    assert ll.sum() == pytest.approx(R_VINE_LOGLIK, rel=1e-9)
    np.testing.assert_allclose(ll[:5], R_VINE_FIRST, rtol=1e-9)
    # VineCopula's matrix, codes and parameters written and read back
    U = V.simulate_vine(trees, 4, 500, np.random.default_rng(0))
    fit = V.FittedVine(("a", "b", "c", "d"), "rvine", tuple(tuple(t) for t in trees), U, U, np.ones(4), np.zeros(4))
    vc = fit.to_vinecopula()
    back = V.from_matrix(vc["matrix"], vc["family"], vc["par"], vc["par2"])
    np.testing.assert_allclose(V.propagate(U, back)[0], V.propagate(U, trees)[0], rtol=1e-12)
    assert (vc["family"] > 100).sum() == 2  # the Tawn edges, each in its orientation's code


def _data(fam, n=1500, seed=3):
    U = cp.sample_copula(fam, _p(fam), n, 2, np.random.default_rng(seed))
    x = stats.norm.ppf(U) * 0.01
    idx = pd.period_range("2001-01-01", periods=n, freq="D", name="time")
    return Dataset.from_frame(pd.DataFrame(x, columns=["a", "b"], index=idx))


def test_through_the_api():
    data = _data("tawn1")
    fit = copula(data, ["a", "b"], family="tawn1")
    assert set(fit.params) == {"theta", "psi", "loglike"} and "psi" in str(fit.summary())
    assert fit.tail_dependence()["upper"] > 0.2
    table = compare_copulas(data, ["a", "b"], families=["gumbel", "tawn1", "tawn2", "bb6", "bb8"])
    aic = dict(zip(table.index, [r[3] for r in table.rows]))
    assert aic["tawn1"] < aic["gumbel"]
    # in a vine, among every pair family
    tri = _data("tawn1", 1500, 4)
    frame = tri.frame.assign(c=np.random.default_rng(9).normal(0, 0.01, 1500))
    vine = vine_copula(Dataset.from_frame(frame), ["a", "b", "c"], families="all")
    assert any(e.family.startswith("tawn") for e in vine.trees[0])
    assert "tawn" in str(vine.summary())
    vine2 = vine_copula(Dataset.from_frame(frame), ["a", "b", "c"], families=["indep", "gaussian", "bb6", "bb8_90", "tawn2"])
    assert {e.family for e in vine2.edges} <= {"indep", "gaussian", "bb6", "bb8_90", "tawn2"}

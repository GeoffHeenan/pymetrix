SETS = {"bb6": (2.0, 1.3), "bb8": (4.0, 0.8), "tawn1": (3.0, 0.5), "tawn2": (1.8, 0.7), "bb1": (0.6, 1.4), "bb7": (1.5, 0.8)}
NEW = [f for f in cp.FAMILIES if f.split("_")[0] in SETS and f not in ("bb1", "bb7")]


def _p(f):
    return dict(zip(cp.ARCH[f].names, SETS[f.split("_")[0]]))


@pytest.mark.parametrize("fam", NEW)
def test_density_cdf_h(fam):
    par = _p(fam)
    f = cp.ARCH[fam]
    pp = tuple(par.values())
    # the density integrates to one over the square
    total = integrate.dblquad(lambda y, x: float(np.exp(f.logpdf(np.array([[x, y]]), pp))[0]), 0, 1, 0, 1,
                              epsabs=1e-9, epsrel=1e-9)[0]
    assert total == pytest.approx(1.0, abs=1e-6)
    # uniform margins; the mixed derivative of the CDF is the density, its derivative in u the h-function
    g = np.linspace(0.07, 0.93, 7)
    a, b = np.meshgrid(g, g)
    a, b = a.ravel(), b.ravel()
    np.testing.assert_allclose(f.cdf(np.column_stack([a, np.ones_like(a) - 1e-15]), pp), a, atol=1e-12)
    np.testing.assert_allclose(f.cdf(np.column_stack([np.ones_like(b) - 1e-15, b]), pp), b, atol=1e-12)
    e = 1e-4

    def C(x, y):
        return f.cdf(np.column_stack([x, y]), pp)

    mixed = (C(a + e, b + e) - C(a + e, b - e) - C(a - e, b + e) + C(a - e, b - e)) / (4 * e * e)
    np.testing.assert_allclose(mixed, np.exp(f.logpdf(np.column_stack([a, b]), pp)), rtol=1e-5)
    e = 1e-6
    np.testing.assert_allclose((C(a + e, b) - C(a - e, b)) / (2 * e), f.h(a, b, pp), rtol=1e-6, atol=1e-9)
    # the inverse h-function inverts it
    w = np.linspace(0.01, 0.99, a.size)
    np.testing.assert_allclose(f.h(a, f.hinv(a, w, pp), pp), w, atol=1e-9)


@pytest.mark.parametrize("fam", ["bb6", "bb8", "tawn1", "tawn2", "bb6_180", "bb8_90", "tawn1_90", "tawn2_270", "bb1_270", "bb7_180"])
def test_simulation_reproduces_tau(fam):
    par = _p(fam)
    U = cp.sample_copula(fam, par, 20_000, 2, np.random.default_rng(11))
    whole = stats.kendalltau(U[:, 0], U[:, 1])[0]
    batches = [stats.kendalltau(*U[i:i + 1000].T)[0] for i in range(0, 20_000, 1000)]
    se = np.std(batches, ddof=1) / np.sqrt(len(batches))
    assert abs(whole - cp.copula_tau(fam, par)) < 3 * se
    for j in range(2):
        assert stats.kstest(U[:, j], "uniform").pvalue > 1e-3



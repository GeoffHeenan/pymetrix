def _family(code):
    return V.VC_FAMILY[int(code)]


def _par(family, p, p2):
    names = cp.ARCH[family].names
    return dict(zip(names, (abs(p), abs(p2))))


@pytest.mark.parametrize("key", list(R_PAIRS))
def test_against_vinecopula(key):
    code, p, p2 = key
    ref = R_PAIRS[key]
    fam = _family(code)
    par = _par(fam, p, p2)
    pp = tuple(par.values())
    U = np.column_stack([U1, U2])
    # at the corner (0.999, 0.997) R's BB6 loses digits (up to 1e-7; ours agrees with the same formula in 80-bit long
    # double arithmetic to 1e-14): 1e-6 there
    corner = 1e-6 if code % 10 == 8 and code < 100 else 1e-8
    for name, ours in (("pdf", np.exp(cp.copula_logpdf(fam, par, U))), ("cdf", cp.copula_cdf(fam, par, U)),
                       ("h1", V.pair_h1(fam, pp, U1, U2)), ("h2", V.pair_h2(fam, pp, U1, U2))):
        np.testing.assert_allclose(ours[:6], ref[name][:6], rtol=1e-8, atol=1e-14, err_msg=name)
        assert ours[6] == pytest.approx(ref[name][6], rel=corner), name
    tau = cp.copula_tau(fam, par)
    assert tau == pytest.approx(ref["tau_hp"], abs=1e-9)
    assert tau == pytest.approx(ref["tau"], abs=2e-7)  # BiCopPar2Tau: R's integrate at its default tolerance
    td = cp.tail_dependence(fam, par)
    assert (td["lower"], td["upper"]) == pytest.approx(ref["tail"], abs=1e-12)



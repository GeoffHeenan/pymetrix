"""The chart gallery runs from start to finish, every figure in it draws, and matplotlib alone draws each one too.

``examples/gallery/chart_gallery.ipynb`` shows every kind of chart pymetrix draws; students and users copy from it,
so it must stay current with the code."""

import json
import sys
from pathlib import Path

import pytest

pytest.importorskip("matplotlib")

GALLERY = Path(__file__).parents[1] / "examples" / "gallery" / "chart_gallery.ipynb"


@pytest.fixture(scope="module")
def gallery():
    """The gallery's namespace after running every code cell, as a reader would, in order."""
    import matplotlib

    matplotlib.use("Agg")
    ns: dict = {"__name__": "__main__"}
    for i, cell in enumerate(json.loads(GALLERY.read_text(encoding="utf-8"))["cells"]):
        if cell["cell_type"] == "code":
            source = "".join(cell["source"])
            try:
                exec(compile(source, f"{GALLERY.name}[{i}]", "exec"), ns)  # noqa: S102 - our own example
            except Exception as exc:  # pragma: no cover - shows which cell failed
                raise AssertionError(f"{GALLERY.name}, cell {i} failed: {exc}\n{source}") from exc
    return ns


def _figures(ns: dict) -> dict:
    from pymetrix import Figure

    return {name: value for name, value in ns.items() if name.startswith("fig_") and isinstance(value, Figure)}


def test_every_figure_in_the_gallery_draws(gallery):
    from pymetrix import house_style

    figures = _figures(gallery)
    assert len(figures) >= 25  # a figure for every kind of chart
    for name, fig in figures.items():
        drawn = fig.draw()
        assert drawn.axes, name
    assert house_style() == ()  # the gallery puts the house style back
    kinds = {type(layer).__name__ for fig in figures.values() for panel in fig.panels for layer in panel.drawn()}
    assert {"Line", "Bars", "Band", "Scatter", "Histogram", "Box", "Ecdf", "Hist2d", "Estimates", "Heatmap", "QQ", "Rule", "Violin", "Hexbin",
            "Contour", "Surface", "Line3d"} <= kinds


def test_matplotlib_alone_draws_every_gallery_figure(gallery):
    import matplotlib
    import matplotlib.pyplot as plt

    for name, fig in _figures(gallery).items():
        code = fig.matplotlib_code()
        assert "import pymetrix" not in code and "from pymetrix" not in code, name
        ns: dict = {"__name__": "standalone"}
        plt.close("all")  # the scripts' earlier figures
        ipython = sys.modules.pop("IPython", None)  # as a plain script runs (see test_figures._run_standalone)
        try:
            matplotlib.use("Agg")
            exec(compile(code, f"{name}.py", "exec"), ns)  # noqa: S102 - generated by pymetrix
            ns["fig"].canvas.draw()
        except Exception as exc:  # pragma: no cover - shows which figure failed
            raise AssertionError(f"the matplotlib script of {name} failed: {exc}") from exc
        finally:
            if ipython is not None:
                sys.modules["IPython"] = ipython


def test_the_gallery_lists_the_pymetrix_it_uses_and_has_no_outputs():
    from pymetrix.testing import check_api_reference

    check_api_reference(GALLERY)
    nb = json.loads(GALLERY.read_text(encoding="utf-8"))
    code = [c for c in nb["cells"] if c["cell_type"] == "code"]
    assert all(not c["outputs"] and c["execution_count"] is None for c in code), "clear the gallery's outputs before committing"
